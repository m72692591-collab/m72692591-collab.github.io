export function buildSitePrompts(input = {}) {
  const brief = buildSiteBrief(input);
  return STAGES.map((stage, i) => ({
    ...stage,
    prompt: [
      "ЭТАП " + stage.id + ". " + stage.title.toUpperCase(),
      "Действуй как опытная команда по разработке и проверке сайтов.",
      "",
      brief,
      "",
      "Задача этого этапа:",
      ...instructions[i].map(line => "• " + line),
      "",
      "Результат: конкретный проверяемый материал для следующего этапа.",
      "Найденные пробелы отмечай как вопросы, не выдумывай ответы."
    ].join("\n")
  }));
}

function runBrowser() {
  const form = document.querySelector("#site-form");
  const list = document.querySelector("#prompt-list");
  const status = document.querySelector("#factory-status");
  if (!form || !list || !status) return;
  const data = () => Object.fromEntries(
    questions.map(([name]) => [name, form.elements.namedItem(name)?.value ?? ""])
  );
  const report = message => { status.textContent = message; };
  const render = () => {
    const prompts = buildSitePrompts(data());
    for (const stage of prompts) {
      const pre = list.querySelector('[data-prompt="' + stage.id + '"]');
      if (pre) pre.textContent = stage.prompt;
    }
    const preview = document.querySelector("#brief-preview");
    if (preview) preview.textContent = buildSiteBrief(data());
  };
  const copy = async text => {
    if (!navigator.clipboard?.writeText) {
      report("Копирование недоступно. Раскройте запрос и выделите текст вручную.");
      return;
    }
    try {
      await navigator.clipboard.writeText(text);
      report("Текст скопирован.");
    } catch (_) {
      report("Браузер запретил копирование. Раскройте запрос и выделите текст вручную.");
    }
  };
  list.addEventListener("click", event => {
    const button = event.target.closest("button[data-copy]");
    if (!button) return;
    const stage = buildSitePrompts(data()).find(item => item.id === button.dataset.copy);
    if (stage) void copy(stage.prompt);
  });
  document.querySelector("#copy-all")?.addEventListener("click", () => {
    void copy(buildSitePrompts(data()).map(item => item.prompt).join("\n\n" + "=".repeat(48) + "\n\n"));
  });
  document.querySelector("#save-brief")?.addEventListener("click", () => {
    const blob = new Blob(["\ufeff", buildSiteBrief(data())], { type: "text/plain;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = "MAESTRO_site_brief.txt";
    document.body.append(link);
    link.click();
    link.remove();
    window.setTimeout(() => URL.revokeObjectURL(url), 1000);
    report("Черновик подготовлен для сохранения на устройстве.");
  });
  form.addEventListener("submit", event => event.preventDefault());
  form.addEventListener("input", render);
  form.addEventListener("change", render);
  render();
}

if (typeof document !== "undefined") {
  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", runBrowser, { once: true });
  } else {
    runBrowser();
  }
}
